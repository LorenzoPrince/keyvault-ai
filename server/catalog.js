// Nivel de exigencia para el badge de la tarjeta, según la placa mínima que pide el juego.
const requirementTier = ({ platform, minGpuScore }) => {
  if (platform === 'Xbox') return 'console';
  if (minGpuScore < 30) return 'low';
  return minGpuScore < 75 ? 'medium' : 'high';
};

const describeSpecs = ({ platform, os, storage }, cpu, gpu, ramGb) =>
  platform === 'Xbox'
    ? `Consola ${os}, ${storage}`
    : `${os}; CPU ${cpu}; GPU ${gpu}; ${ramGb} GB de RAM; ${storage}`;

// Catálogo en memoria: el stock se reinicia con cada arranque del servidor.
export const products = catalog.map((product) => ({
  ...product,
  requirementTier: requirementTier(product),
  minSpecs: describeSpecs(product, product.minCpu, product.minGpu, product.minRamGb),
  recSpecs: describeSpecs(product, product.recCpu, product.recGpu, product.recRamGb),
}));
